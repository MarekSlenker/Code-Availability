  x[x == "0|0|0|1"] = 1     # 0.25
  x[x == "0|0|1|1"] = 1
  x[x == "0|1|1|1"] = 1
  x[x == "0|0|0|0|1"] = 1 # 0.2
  x[x == "0|0|0|1|1"] = 1
