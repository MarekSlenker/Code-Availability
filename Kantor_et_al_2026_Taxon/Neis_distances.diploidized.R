  x[x == "0|1|1|1|1"] = 1
  x[x == "0|0|0|0|0|1"] = 1 # 0.167
  x[x == "0|0|0|0|1|1"] = 1
  x[x == "0|0|0|1|1|1"] = 1
  x[x == "0|0|1|1|1|1"] = 1
  x[x == "0|1|1|1|1|1"] = 1
  x[x == "0|0|0|0|0|0|1"] = 1 # 0.143
